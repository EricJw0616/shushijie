def _anchor_ok(pat):
    """锚点是否可用。四字以上一律可用；两字仅白名单内可用。"""
    if len(pat) >= MIN_ANCHOR:
        return True
    return pat in SHORT_OK


def _balance_quotes(parts):
    """把被句末标点切开的引语接回去。

    底本里「子曰：「不得中行而與之，必也狂狷乎！狂者進取，狷者有所不為也。」」
    这种引语**内部含句末标点**，按标点切必然断在引号中间，切出两种残句：

      · 有「无」 —— 子曰：「中庸之為德也，其至矣乎！
      · 有」无「 —— 狂者進取，狷者有所不為也。」

    两种引出去都是半句话。这里按引号计数逐句拼接，直到配平为止。

    ## 为什么要保留两种切法，而不是只留拼接结果
    底本的引号不全配对（漏一个 」，或嵌套只写一层）。一旦漏了 」，后面
    所有句子都会被当成「引语还没结束」吞进同一条，超长后被长度闸门丢掉
    —— 实测《三国志演义》这样丢了 189 处命中（「守成」「信義」都丢了）。
    cap 截断治不了根：撤回拼接仍会丢掉「已经吞进去的那几片」。

    所以这里**两种切法都交出去**：拼接片 + 原始未拼接片，由 sents 层做
    「短的是长的子串就丢短的」去重。完整引语优先留，被误吞的独立句也留，
    一个都不丢。
    """
    OPEN, CLOSE = '「『“', '」』”'
    out, buf = [], None
    for p in parts:
        buf = p if buf is None else buf + p
        unclosed = sum(buf.count(c) for c in OPEN) - sum(buf.count(c) for c in CLOSE)
        if unclosed > 0:
            continue                    # 引语未闭合，继续接
        out.append(buf)
        buf = None
    if buf:                             # 段末仍未闭合：原文本身缺引号，照收
        out.append(buf)
    return out, list(parts)


def _dedup_sub(sents):
    """短句是长句的子串就丢短句。

    只用于「原始片 vs 拼接片」的合并：拼接片是原始片的超集，
    所以只要原始片完整落在某个拼接片里，它就已经被覆盖了，
    留着会让同一段原文在同一议题下出两条重复证据。
    """
    if len(sents) <= 1 or len(sents) > 240:      # 超长段不做，避免 O(n²)
        return sents
    keep = []
    pool = sorted(set(sents), key=len, reverse=True)
    for s in pool:
        if not any(s != k and s in k for k in keep):
            keep.append(s)
    return keep


def _sentences(text):
    """把一段切成句子。古文断句靠。！？；，整句是一个完整判断。

    ## 为什么要有「逗号兜底」这条分支
    《左传》这类底本逗句比 24.2（全篇用逗号断句、段末才用句号），
    实测有一段 315 字却只有 2 个句号 —— 按句号切只能得到 1 个巨型「句子」，
    超长被丢掉，于是这本书在所有议题上都命中不到。
    这类文本的**真实句界在逗号**，必须按逗号切，否则等于放弃这本书。

    判据不靠猜：句号密度 < 3/千字就当逗句体处理。
    """
    t = (text or '').strip()
    if not t:
        return []
    # 句末标点太少 → 逗句体，按逗号切
    han = len(re.findall(r'[\u4e00-\u9fff]', t))
    ends = len(re.findall(r'[。！？；]', t))
    dense = han and ends * 1000.0 / han >= 3
    # 句界必须在「句末标点 + 可选的右引号」之后。
    # 只按 [。！？；] 切会把《论语》的「子曰：「…。」」切成两半：
    # 实测切出「」2. 子曰：「詩三百…」这种以右引号开头的残句，
    # 引用出去读者看到的是半句话。加 」』” 收尾后才是完整的引语。
    sep = (r'(?<=[。！？；][」』”])|(?<=[。！？；](?![」』”]))'
           if dense else
           r'(?<=[。！？；，][」』”])|(?<=[。！？；，](?![」』”]))')
    parts = re.split(sep, t)
    merged, raw = _balance_quotes(parts)
    lo = 4 if dense else 6
    # 顺序不能反：先过长度闸门，再做子串去重。
    # 若先去重，一条 300 字的拼接串会把里面每一片原始句都判成「已被覆盖」，
    # 而它自己又超长被丢掉 —— 结果是两条都没了（实测丢 189 处就是这个原因）。
    pool = [x.strip('， ').strip() for x in (merged + raw)]
    pool = [x for x in pool if x and lo <= len(x) <= 200]
    return _dedup_sub(pool)


def _find(pat, sent, full=None):
    """在一句里找锚点，返回命中的**整句**（证据要整句才看得出语境）。

    三条排除（都是实测撞过的）：
      1. 锚点落在《》书名内部 → 弃（「中庸》《大学》」不是中庸这一议题）
      2. 整句是「甲，乙」式三字以内短名罗列 → 弃（「君，西周君」不是君君臣臣）
      3. 锚点不可用（长度不足且不在白名单） → 弃

    另有一条补全：整句不足 12 字时，向后扩到下一句（至多 60 字）。
    实测《论语》「子曰：「色難。」」只有 8 字，单看这句读者不知道在说什么；
    补成「子曰：「色難。有事，弟子服其劳…」」才有语境。
    补全后的片段仍必须是原文的子串 —— 由调用方再校验一次。
    """
    if not _anchor_ok(pat):
        return None
    if pat not in sent:
        return None
    i = sent.index(pat)
    for bm in re.finditer(r'《[^》]{1,20}》', sent):
        if bm.start() <= i < bm.end():
            return None
    parts = [x for x in re.split(r'[，、]', sent) if x]
    if parts and all(len(x) <= 3 for x in parts):
        return None
    # 两字锚点前面紧接否定词时，语义常被反转或切断：
    # 《孟子》「不知足之蹈之」实际是「不知 / 足之蹈之」，
    # 与「知足」这个议题无关。两字锚点一律要求前面不是「不/未/無/莫」。
    if len(pat) <= 2 and i > 0 and sent[i - 1] in '不未無无莫':
        return None
    # 太短的句子补上后半句，否则引出去读者看不懂。
    # 但已经收在右引号上的不要再扩 —— 那是自成一句的完整引语：
    # 「子曰：「過猶不及。」」只 10 字，补全会把下一条「子謂子夏曰…」吞进来，
    # 序号（「16.」）也跟着带出，引出去就不干净了。
    _closed = re.search(r'[。！？；][」』”]$', sent) is not None
    if len(sent) < 12 and full and not _closed:
        j = full.find(sent)
        if j >= 0:
            tail = full[j:j + 60]
            k = tail.find('。', len(sent))
            if k > 0:
                tail = tail[:k + 1]
            if tail and tail in full:
                return _strip_seq(tail)
    return _strip_seq(sent)


def _strip_seq(s):
    """去掉段内的条目序号（「9. 子曰…」「三十五孟子曰…」）。

    这些序号是底本的编目，不是原文的一部分。留着有两个问题：
      1. 引用出去不干净；
      2. 序号会随切分点变化，导致同一段原文出现两种文本，回查对不上。
    去掉后仍是原文子串（只切掉前缀），回查不受影响。
    """
    return re.sub(r'^[0-9]{1,3}[.．、]\s*|^[一二三四五六七八九十百]{1,3}(?=[\u4e00-\u9fff])',
                  '', s)


def match_book(segs, argu_anchors=None, min_hits=1, max_evidence=12):
    """一本书 → 议题标签候选。**每个议题一张卡，卡里带全部命中段**。

    返回 [{议题, 代号, 情绪词, 受众词, 锚点, 原文, 证据, 依据, 性质, 命中数}]

    · 只找**正文段**（篇序>0），跳过目录页。
    · 证据按「论断段优先」排序后取前 max_evidence 段：
      论断段是讲道理的段，比叙事段更适合做素材；
      但不删多余的，命中数照实报（页面显示「命中 N 段，列前 12」）。
    · 证据必须是**整句**，且能在该段里逐字查到。
    """
    out = []
    argu_anchors = argu_anchors or set()
    for th in THEMES:
        hits = []
        for s in segs:
            if s.get('篇序', 0) <= 0:
                continue
            t = s.get('文本') or ''
            sent = None
            for snt in _sentences(t):
                for pat in th['pats']:
                    sent = _find(pat, snt, full=t)
                    if sent:
                        break
                if sent:
                    break
            if not sent or sent not in t:
                continue
            hits.append({
                '锚点': s['id'],
                '原文': sent,
                '论断段': s['id'] in argu_anchors,
                '篇': s.get('篇', ''),
            })
        if len(hits) < min_hits:
            continue
        total = len(hits)
        hits.sort(key=lambda x: (not x['论断段'], x['锚点']))
        keep = hits[:max_evidence]
        out.append({
            '议题': th['name'], '代号': th['id'],
            '情绪词': list(th['emo']), '受众词': list(th['aud']),
            '锚点': keep[0]['锚点'], '原文': keep[0]['原文'],
            '证据': keep,
            '依据': th['note'],
            '性质': '今用（整理者判断，非作者原分类）',
            '命中数': total,
            '论断段数': sum(1 for h in hits if h['论断段']),
        })
    return out


def coverage(book_rows):
    """议题覆盖。必须与「有命中」分开报：没命中可能是书里真没有，
    也可能是我们没找到表达方式，两种性质不同，页面要能看出来。"""
    got = {r['代号'] for r in book_rows}
    miss = [{'代号': t['id'], '议题': t['name']} for t in THEMES if t['id'] not in got]
    return got, miss


