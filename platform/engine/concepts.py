# -*- coding: utf-8 -*-
"""概念层（L4-概念）：把「书里在讲道理的地方」定位出来，并把可指认的命题词抽出来。

━━ 这个模块为什么长成这样 ━━
需求是「热点解析后做标签匹配」，也就是：给定一个概念（如「隐忍」「权力」），
找出哪些书讲过、讲在哪一段。为此必须有一层概念标签。

我实测过五条「纯自动抽概念」的路，全部不通，记录在此以免后人重试：

  1. 定义句式法   X者…也 / 所谓X / 何谓X
     → 全库仅 14 个词过关。原因：篇名是标题，正文不会回头定义它。
       篇名「审虚实」在全书只出现 1 次 —— 标题不参与正文论述。

  2. 论断框架词   所谓X / X之道 / X之理
     → 跨 ≥3 书仅 14 个（君子 7、先王 5、圣人 3…），其中 2 个是「此百世不易」
       这类跨句假词，真词率 85%，但总量太小，撑不起一层。

  3. 虚词邻接抽名   名词 + 者/也/而/之
     → 抽出「而已」「之人」「之法」「未之有」等，全是虚词组合。
       与之前踩过的「左右邻字熵抽词」同一个坑：虚词分布最自由，必然排前。

  4. 篇名片段       从作者拟的篇名里切 2-3 字
     → 排前 16 个全是「十五」「第十」「十六」等序号碎片。

  5. 书内共现簇     高频词的同段共现
     → 种子「天下」在孟子的邻接是「不仁/君子/尧舜」，在三国演义是
       「将军/英雄/玄德」，在徐霞客是「五里/大道」。**同一个词在不同书
       指向完全不同的论域**，做全局主题词表必然串味。

━━ 结论与做法 ━━
纯机器「抽概念」做不到：概念是读出来的，不是数出来的。但机器能做准另一件事：
**定位「哪一段在讲道理」**。这已经足够支撑引用层的召回——
热点来的时候，先按论断段召回候选段落，再让人（或下游模型）在其中挑。

所以本层只出两种东西，且严格分级：
  · 论断段（定位器，L4-概念 层的 **段级** 标签）
      判据只用强推论标记，不用「盖」（游记里多是「覆盖/因为」，实测徐霞客
      391 段命中里绝大多数不是论断，是假的）。
      每条带锚点 + 触发词 + 原文，可逐条回查。
  · 命题词（仅当在同一本书内被 ≥N 次论断性使用，才出）
      不跨书合并、不做同义词归并。宁可一书本一条，也不拼一张假主题表。

**产出的性质是「定位器」，不是「主题标签」。** 页面上必须这么标。
把它当主题标签用，就会出现「搜权力，出来一堆讲『权』字的游记」。
"""
import re, io, os, json, sys
from collections import Counter, defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

# ── 强推论标记 ──────────────────────────────────────────────
# 刻意不含「盖」：文言「盖」有三义（覆盖/因为/推测），游记与地理书中
# 绝大多数非论断。实测徐霞客 391 段命中里绝大多数不是议论，故剔除。
# 也不含「夫」单字：起句发语词太泛，散文里遍地都是。
RE_ARG = re.compile(
    r'(故曰|是以|是故|此言|此謂|此谓|何謂|何谓|'
    r'故凡|故聖|故圣|故君|故先王|故曰|'
    r'凡[^。！？]{2,12}者[，,][^。！？]{4,60}也)')

# 对话密集段**不再排除**。
# 原来用「段内对话标记 ≥2 就排除」想把小说对白挡在外面，
# 实测这个判据完全无效：论语 100%、孟子 97%、世说新语 99.6% 全是对话体，
# 而红楼梦 94.8%、三国演义 96.2% 也全是对话体 —— 两者用同一个数字区分不了。
# 代价是论语这本最典型的论断书被判成 0 段论断，等于把最重要的书漏掉。
# 现在的做法：不排除对话，只要求段内有论断结构（见 is_argu）。
# 命题性对话（子曰「…」、孟子曰「…」）本来就是论断，不该被挡。

# 段长窗口：太短没有论证结构，太长是多事并记（游记一天一记）
LEN_MIN, LEN_MAX = 60, 700


def is_argu(text):
    """判断一段是否为论断段。返回 (是否, 触发词)。"""
    if not (LEN_MIN <= len(text) <= LEN_MAX):
        return False, ''
    m = RE_ARG.search(text)
    if not m:
        return False, ''
    return True, m.group(1)


def argus(segs):
    """从 segments 抽出全部论断段。返回 [{锚点,篇,触发,原文}]。"""
    out = []
    for s in segs:
        if s.get('篇序', 0) <= 0:
            continue
        ok, trig = is_argu(s.get('文本') or '')
        if ok:
            out.append({'锚点': s['id'], '篇': s.get('篇', ''),
                        '触发': trig, '原文': s.get('文本') or ''})
    return out


# ── 命题词：实测判定为不可用，不产出 ──────────────────────
# 保留这段代码是为了记录「试过、不行、别再试」，不是为了产出。
#
# 阈值放到 1（即不设阈）时全库 181 个，抽查前 20 个：
#   可用   吉凶、悔吝、刚柔、自然、君臣、天地、日月（易经/礼记/史记里的真概念）
#   垃圾   可痛哭、去二國死兩君、青黑緣、凡合笋使就、雕刻使成、凡音
# 垃圾占七成以上，且没有任何机器判据能分开这两类 —— 它们的句法形态完全一样。
# 阈值提到 4 就归零。也就是说：要么全收（七成假），要么全丢（一个不剩）。
#
# 这个结果本身就是结论：**概念不能靠定型句式抽**。概念是读出来的。
# 与其在页面上摆 181 个半真半假的词，不如一个都不出，把论断段交给下游。
def props_disabled(seg_rows, min_n=4):
    """已停用。见上方说明：定型句式抽出的命题词七成是跨句碎片。"""
    return []


def build(segs):
    """一本书 → 概念层产出。

    只出论断段（定位器）。命题词已在实测后停用，见 props_disabled 说明。
    """
    a = argus(segs)
    return {
        '论断段': a,
        '命题词': [],          # 停用，恒为空；字段保留以免下游 KeyError
        '性质': '定位器',
        '边界': ('论断段=有强推论标记（故曰/是以/何谓/凡…者…也）且非对话密集的段落，'
                 '供热点召回候选段落。本层**不出主题词**：实测定型句式抽出的命题词'
                 '七成是跨句碎片（「可痛哭」「去二国死两君」），宁可不出，不出假词。'),
    }


def gap_note(n_argu):
    """给标签库写「这一层做了什么、缺什么」，避免页面显示成有。"""
    if n_argu == 0:
        return ('本书未抽出论断段：正文无强推论标记（故曰/是以/何谓/凡…者…也），'
                '多为叙事、对白、条目或韵文。这是文体差异，不是抽取失败。')
    if n_argu < 5:
        return f'论断段仅 {n_argu} 段，样本偏少，召回覆盖率低'
    return ''


if __name__ == '__main__':
    LIB = 'D:/workbuddy/图书蒸馏/platform/library'
    segs = [json.loads(l) for l in io.open(f'{LIB}/segments.jsonl', encoding='utf-8') if l.strip()]
    byb = defaultdict(list)
    for s in segs:
        byb[s['书']].append(s)
    ta = 0
    for b, rows in sorted(byb.items()):
        r = build(rows)
        ta += len(r['论断段'])
        print(f"{b:<18} 论断段 {len(r['论断段']):>4}  {gap_note(len(r['论断段']))}")
    print(f'\n合计 论断段 {ta}')