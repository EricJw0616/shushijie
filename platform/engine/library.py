_PRINTED_TITLE = re.compile(r'《(?P<name>[^《》\n]{1,40})》')
_HISTORICAL_CITATION = re.compile(
    r'(?:根据|根據|据|據|引自|参见|參見|详见|詳見)\s*'
    r'(?P<name>(?:清|明|元|宋|辽|遼|金)[\u3400-\u9fff]{1,6}(?:实录|實錄))'
    r'\s*(?:所载|所載|所记|所記|记载|記載|卷[一二三四五六七八九十百零〇\d]+)')
_NON_EVIDENCE_ROLES = {'toc', 'table', 'vertical', 'cover', 'copyright', 'header', 'footer',
                       'caption', 'front_matter'}
_NON_TITLES = {'本书', '前书', '此书', '同前书', '同上', '書名', '书名', '目录', '目錄', '原文'}
_TITLE_FRAGMENTS = {'会典', '會典', '全集', '全书', '全書', '实录', '實錄', '年谱', '年譜'}
_REFERENCE_DAMAGED = re.compile(r'《\s*》')
_REFERENCE_CUE = re.compile(r'(?:根据|根據|参见|參見|引自|详见|詳見|另见|另見|据|據)\s*$')
_REFERENCE_LOCATOR = re.compile(r'(?:卷[一二三四五六七八九十百〇\d]+.{0,8}页|[页頁][一二三四五六七八九十百〇\d]+)')


def name_evidence_segment(row):
    role = row.get('source_role') or row.get('source_kind')
    return (not any(row.get(key) for key in ('source_structure_suspect', 'source_layout_suspect', 'source_issue'))
            and role not in _NON_EVIDENCE_ROLES)


def book_name_signals(text):
    """Find a printed title or a named historical source with an explicit citation cue."""
    text = text or ''
    damaged = _REFERENCE_DAMAGED.search(text)
    hits = []
    for pattern, signal in ((_PRINTED_TITLE, 'printed_title'), (_HISTORICAL_CITATION, 'citation')):
        for match in pattern.finditer(text):
            name = match['name'].strip()
            if (len(HAN.findall(name)) < 2 and not re.search(r'[A-Za-z]{2}', name)) or name in _NON_TITLES:
                continue
            if signal == 'printed_title' and (name in _TITLE_FRAGMENTS or _REFERENCE_LOCATOR.search(name) or
                    (damaged and not _REFERENCE_CUE.search(text[max(0, match.start()-12):match.start()]))):
                continue
            hits.append((name, match.group(0), signal))
    return hits


def names(segs, topk=200):
    """专名表：书名/篇名、称谓、外文名、机构名。带首现锚点与分布。"""
    PAT = [
        ('书名篇名', r'《[^》]{1,24}》'),
        ('称谓', r'[\u4e00-\u9fff]{1,4}(?:先生|太太|夫人|小姐|公子|老爷|大人|道长|师父)'),
    ]
    agg = {}
    for s in segs:
        for cls, pat in PAT:
            for mm in re.finditer(pat, s['文本']):
                w = mm.group(0)
                if len(w) < 2:
                    continue
                k = (cls, w)
                a = agg.setdefault(k, {'词': w, '类': cls, '频次': 0,
                                       '首现': s['id'], '篇': set()})
                a['频次'] += 1
                a['篇'].add(s['篇'])
        if not name_evidence_segment(s):
            continue
        for name, quote, evidence in book_name_signals(s['文本']):
            if evidence == 'printed_title':
                continue
            key = ('书名篇名', '《' + name + '》')
            row = agg.setdefault(key, {'词': key[1], '类': key[0], '频次': 0,
                                       '首现': s['id'], '篇': set()})
            row.setdefault('证据锚点', s['id'])
            row.setdefault('证据原文', quote)
            row['频次'] += 1
            row['篇'].add(s['篇'])
    out = []
    for a in agg.values():
        a['分布篇数'] = len(a['篇'])
        a['篇'] = sorted(a['篇'])
        out.append(a)
    out.sort(key=lambda x: -x['频次'])
    return out[:topk]


def qupai_kejie(segs):
    """曲牌 / 科介索引（仅戏曲型有值，其余返回空，不伪造成果）。"""
    q, qf = Counter(), {}
    k, kf = Counter(), {}
    for s in segs:
        for w in re.findall(r'【[^】]{1,8}】', s['文本']):
            q[w] += 1
            qf.setdefault(w, s['id'])
        for w in re.findall(r'[\[［][^\]］]{1,12}介[\]］]', s['文本']):
            k[w] += 1
            kf.setdefault(w, s['id'])
    qp = [{'曲牌': w, '频次': n, '首现': qf[w]} for w, n in q.most_common()]
    kj = [{'科介': w, '频次': n, '首现': kf[w]} for w, n in k.most_common()]
    return qp, kj


