    # --- D 通道：常见引述人物 ---
    # 学术/思想类书里，孔子、孟子、老子这类人常以「孔子说」「孟子曰」出现，
    # 但不对白、姓氏法又因无对白证据被挡；这里按常见引述人物补候选。
    # 不是通用 NER：只覆盖人文书里高频引用的人物；其余仍靠姓氏法/人工。
    CITED = ('孔子', '孟子', '老子', '庄子', '荀子', '墨子', '韩非子', '曾子',
             '子思', '朱子', '颜渊', '子贡', '子路', '子夏', '子游', '杨朱',
             '耶稣', '柏拉图', '亚里士多德')
    have2 = {r['人物'] for r in rows}
    for w in CITED:
        if w in have2:
            continue
        hits = [s for s in segs if w in s['文本']]
        freq = sum(s['文本'].count(w) for s in hits)
        if freq < 2:
            continue
        rows.append({'人物': w, '通名': False, '频次': freq,
                     '首现': hits[0]['id'], '首现篇': hits[0]['篇'],
                     '分布篇数': len({s['篇'] for s in hits}),
                     '姓氏法': 0, '对白归属': 0,
                     '来源': '引述人物·待人工确认', '证据': '强证据'})
        have2.add(w)

    rows.sort(key=lambda x: (-x['对白归属'], -x['频次']))
    # 不再硬截 40 人：红楼梦 400+ 人物，截到 40 会把主角之外的
    # 次重要人物全砍掉，且「强证据人物数」恰好 40 会误导成「只有 40 个」。
    # 改为按证据强度分批：强证据全出，弱证据限 40。
    strong = [r for r in rows if r['证据'] == '强证据']
    weak = [r for r in rows if r['证据'] == '弱证据'][:topk]
    rows = strong + weak
    tot = sum(r['频次'] for r in rows) or 1
    # 第二返回值 pollute 保留原语义（通名污染率），另把能力边界挂在模块级，
    # 由调用方读取：这里必须让下游能区分「这本书没有人」与「我们抽不出」。
    global LAST_ABILITY
    LAST_ABILITY = {
        '句首率门槛已启用': bool(_USE_INI_RATE),
        '状语形态占比': round(_ADV_FORMS / max(1, _C_TOT), 3),
        '说话人法样本数': int(_C_TOT),
        '判定': ('位置特征失效：状语阻断句式占主导，'
                 '人名抽取不可信，人物表仅供定位'
                 if _USE_INI_RATE else '正常'),
    }
    return rows, 0.0


