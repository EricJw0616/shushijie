        # ---- 句首主语率：仅对「位置特征已失效」的书启用 ----
        # 现代白话小说抽人名只能靠位置，而位置有两种：
        #   ① 紧邻说话动词（C）—— 带宽窄，说话动词前 4 字常是状语
        #   ② 本句句首（CS）—— 抓到的是真主语，但句首也可能是「可是/同时」
        #
        # ⚠ 这一条**不能当全局规则**。两次实测教训：
        #   ①「接的率 > 0.45 就丢」——四世同堂有效，但金瓶梅 201→111、
        #     红楼梦 189→46、三国 169→117。文言人名大量处在「寶玉的丫頭」
        #     这类结构里，接的率并不低。
        #   ②「句首率 < 0.12 就丢」——红楼梦 189→98、金瓶梅 201→140。
        #     章回体人物常在句中出现（「只見寶玉走來」），不在句首。
        # 结论：位置类判据只在**这本书的说话人法已经跑偏**时才该生效，
