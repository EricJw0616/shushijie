    # 看着像人名、实则是残词 —— 比抽不出来更糟，因为下游会当成真人物建图谱。
    han_run = re.compile(r'[\u4e00-\u9fff]{2,4}')
    A = Counter()
    for s in segs:
        for run in han_run.findall(s['文本']):
            for L in (3, 2):
                for i in range(len(run) - L + 1):
                    w = run[i:i + L]
                    if _is_xing(w[0]):
                        A[w] += 1

    # B 对白归属：就近窗口法。
    # 现代小说写「声音很低的说：“……”」，人名在更前面很远，
    # 因此以「说话动词+引号」为锚点，向前回看 160 字，取最近的人名候选。
    #
    # 但窗口必须以「句读/引号」为界，否则会跨过一段话抓到上一句的尾巴：
    # 实测「更利害。”寶玉道：“誰都象三妹…」中，锚点前最近的人名是「寶玉」，
    # 若只看 160 字窗口的最末几个字，取到的是「利害」——
    # 「利害」因此被记了 100+ 次对白归属，成了红楼梦的「主要人物」。
    BAD_TAIL = set('的了是在有和就都也很不没这那什么个们着过地说'
                   '要会能可应为所如如果但是而且所以因为')
    anchor = re.compile(r'(?:说道|问道|答道|笑道|叫道|喝道|骂道|道|说|问|答)'
                        r'[:：]?\s*[“「]')
    # 句界：引号收尾、句末标点、感叹/问号
    SENT_END = re.compile(r'[。！？；…\.!?][”」』"]?\s*$')
    B = Counter()
    for s in segs:
        t = s['文本']
        for mm in anchor.finditer(t):
            win = t[max(0, mm.start() - 160):mm.start()]
            # 先按句末/引号把窗口切成句子，只取最后一句 ——
            # 说话人一定与说话动词同句，跨句取的都是上一句的尾巴。
            # 「更利害。”寶玉道：」切成 ['更利害。”', '寶玉']，取最后一句就得「寶玉」，
            # 不会取到「利害」。这一步是修「利害」被当主要人物的关键。
            parts = re.split(r'[。！？；…\.!?][”」』"]?', win)
            tail = parts[-1] if parts else win
            best = None
            for run in reversed(han_run.findall(tail)):
                for L in (3, 2):
                    w = run[-L:]
                    if (len(w) == L and _is_xing(w[0])
                            and w[-1] not in BAD_TAIL and w not in COMMON):
                        best = w
                        break
                if best:
                    break
            if best:
                B[best] += 1

    BAD = {'所以', '必须', '广告', '上面', '那里', '里面', '现在', '于是',
           '大约', '大概', '只是', '一直', '大家', '自己', '什么', '东西',
           '文章', '那么', '都是', '应该', '国的', '别的', '时候', '地方',
           '事情', '问题', '意思', '样子', '人家', '我们', '你们', '他们'}
    # 高错误率尾字：以这些字收尾的「姓+字」几乎都是虚词切出来的
    BAD_TAIL = set('的了是在有和就都也很不没这那什么个们着过地说'
                   '要会能可应为所如如果但是而且所以因为')
    nseg = max(1, len({s['篇'] for s in segs}))
    # --- C 通道：无姓氏依赖的称呼法 ---
    # 为什么必须有这条：中国古典小说的人物常以「名/字/号/身份」出现，
    # 不冠姓。实测：
    #   「寶玉」3923 次，「賈寶玉」仅 17 次 —— 97% 的出现不带姓
    #   「行者」1832 次，「孫悟空」仅 45 次 —— 主角主要靠身份称呼
    #   「西門慶」的「西門」是复姓，单看首字「西」会被当普通字
    # 只靠姓氏法，红楼梦 3923 次的主角一次都抽不出来。
    #
    # 判据换成三条同时成立，不使用姓氏：
    #   ① 该词紧跟说话动词（道/说/问/答）—— 说话人是人物，这是最硬的证据
    #   ② 全书频次 ≥8，分布 ≥3 篇 —— 一次性称呼不是主要人物
    #   ③ 不是虚词、不是动作词、不是地名物名（多道过滤）
    C = Counter()
    # CS = 句首主语法计数（仅现代白话文的状语回退路径使用）。
    # 刻意与 C 分开：C 是「紧邻说话动词」，证据强度远高于「本句句首」，
    # 混在一起会让「可是 / 同时 / 因此」这类句首虚词直接冒充强证据。
    CS = Counter()
    # 说话人位置：词后面紧跟「道/说/问/答/曰」+ 可选「：」+ 引号。
    #
    # 「曰」必须收进来：文言小说一律用「曰」，不用「道/说」。
    # 实测三国志演义「曰：」6292 处、「道：」仅 17 处 ——
    # 只认「道/说」时，三国 41 万字只抽得出 14 个「人物」，
    # 而且全是「探馬報」「細作報」这类非人物；刘关张曹孙一个都进不来。
    # 注意「曰」后面常不带引号（「玄德曰：善。」），所以冒号可选、引号也可选。
    # ---- 现代白话文的「状语阻断」问题 ----
    # 上面这条正则对文言与章回体够用，但对现代白话小说是错的。
    # 老舍的标准句式是「主语 + 状语从句 + 的说」，主语在句首，
    # 中间隔着一个甚至三个分句：
    #   瑞宣先笑了一下，而后声音很低的说
    #   小崔，倭瓜脸气得一青一红的，正和李四爷指手画脚的说
    #   还笑着，可是笑得很不好看，他声音很低，而很清楚的说
    # 只回看 4 个字，切到的一定是状语：
    # 实测四世同堂「强证据 13 人」里塞着「音很低 / 的声音 / 轻轻 / 赶紧 /
    # 极快 / 搭讪 / 迟疑 / 婆妈妈」，而祁老人、白巡长、钱先生、李四爷
    # 这些**真名**全被降成弱证据。这比「抽不出」更糟 ——
    # 它生产的是假强证据，会直接污染图谱。
    #
    # 判据：说话动词前若是「的 / 地」结尾的状语，或紧邻词属于情态词，
    # 就不是说话人。此时回退到**本句句首**取主语。
    _ADV_TAIL = re.compile(
        r'(?:的|地)$|^(?:很低|很高|轻轻|慢慢|慢慢儿|极快|极慢|恳切|严肃|勉强|'
        r'急忙|赶紧|连连|紧跟|迟疑|搭讪|满意|气儿|满脸|满脸赔笑|没有好气|'
        r'不太|不大|很不|十分|非常|相当|异常|格外|颇为|颇)')
    # 状语结构识别：'…的说 / …地问 / …的道'
    _ADV_BEFORE = re.compile(r'(?:的|地)(?:说|说道|问|问道|答|答道|道|嚷|叫)')
    _SENT_END = '。！？；\n：“”「」『』'
    say_after = re.compile(
        r'([\u4e00-\u9fff]{2,4})'
        r'(?:的說道|說道|说道|說|说|問|问|答|曰|云|笑道|叫道|嚷道|罵道|骂道)')
    # ↑ 刻意**不带**冒号与引号：那部分要单独验，不能当成可选尾巴。
    # 若写成 `(?:[:：]?\s*[“「]?)`，正则会把冒号一起吃掉，
    # 于是「后面是不是冒号」永远检查不到 —— 实测按那种写法三国
    # 4796 个匹配只有 16 个通过，人物表塌成 4 人。
    # ↑ 这个模式太宽，什么都能切出来。必须再验一道「确实在引一句人话」：
    #
    # 「曰」不加限制时，文言文里任何「X曰」都被当说话人。实测徐霞客游记抽出
    #   「竟無宿處」→ 竟無（「日已墮，竟無宿處」）
    #   「有坊峙焉」→ 有坊（「當其中有坊峙焉」）
    #   「茫無知者」→ 知者（「土人茫無知者」）
    # 这些词后面跟的根本不是说话动词，是正则把后一个字吃进了动词
    # （「宿」不是，「曰」才是 —— 真元是「茫無知者」后面接「，」）。
    #
    # 可靠的验法：**说话动词之后必须紧跟冒号/引号/句读**，
    # 即「玄德曰：」「宝玉道：“」，而不是「X曰Y」这种连贯短语。
    # 文言确有「玄德曰善」不带冒号，但那种极少；而「X曰Y」的误切是成百上千的。
    # 宁可漏，不可错 —— 误收会在图谱里生成几百条假关系，漏掉只是少一个候选。
    _SAY_OK = re.compile(r'^[:：]|^[“「"『]|^$')
    # 紧跟说话动词、但明显是叙述承接的（「X說道是」「X曰不然」）
    _SAY_BAD_LEAD = set('的了着著过過得地在於于而則则矣焉者也乃即便又'
                        '不無无有之其以所為为與与同和')
    # 贪婪窗口会把动作词吃进名字：「寶玉听說道」→ group(1)='寶玉听'。
    # 处理办法不是改非贪婪（「寶玉听說」本身有歧义），
    # 而是剥离尾部的动作/虚词字：'寶玉听' → '寶玉'。
    _STRIP_TAIL = set('了着著过過得地们的又便就都也还還只才刚剛正将將已未曾'
                      '听聽看说說问問笑叫走跑来來去回上下进出進')

    def _is_say(text, endpos):
        """说话动词之后是否真的在引一句话。"""
        nxt = text[endpos:endpos + 1]
        if nxt == '':
            return True
        if nxt in ':：' or nxt in '“「"『':
            return True
        return False

    def _subject_of(text, vstart):
        """说话动词之前的主语。返回 (候选, 是否走了回退)。

        章回体：「寶玉笑道」→ 紧邻就是主语，直接取。
        现代白话：「瑞宣先笑了一下，而后声音很低的说」→ 紧邻是状语，
        必须回退到句首取主语。用「紧邻"的/地"结尾」与情态词表判状语。
        """
        pre = text[max(0, vstart - 4):vstart]
        # 情况一：紧邻是「…的」或「…地」，或情态词 → 状语阻断，回退句首
        if _ADV_TAIL.search(pre):
            st = vstart - 1
            while st > 0 and text[st - 1] not in _SENT_END:
                st -= 1
            head = text[st:vstart]
            head = head.lstrip('，,、 ')
            m2 = re.match(r'([\u4e00-\u9fff]{2,4})', head)
            if m2:
                return m2.group(1), True
            return None, True
        return None, False

    for s in segs:
        for m in say_after.finditer(s['文本']):
            if not _is_say(s['文本'], m.end()):
                continue
            w = m.group(1)
            while len(w) > 2 and w[-1] in _STRIP_TAIL:
                w = w[:-1]
            C[w] += 1
            # 状语结构另记一份「句首主语」，交给下游按证据强度区分：
            # 主语句首法在没有姓氏表的现代白话小说里是唯一可用信号，
            # 但它比「紧邻说话动词」弱得多（句首可能是时间状语「可是/同时」），
            # 所以单独一个计数器 CS，绝不混进 C。
            sub, fell = _subject_of(s['文本'], m.start())
            if fell and sub and len(sub) >= 2:
                CS[sub] += 1
