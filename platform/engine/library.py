_PERSON_TITLE_LEAD = re.compile(r'^[\u3400-\u9fff]{2,4}')
_PERSON_SOURCE_MARKER = (
    r'[ⅠⅡⅢⅣⅤⅥI.V…①②③\s]{0,24}[（(]\s*\d{3,4}\s*[—–\-~～至]\s*\d{3,4}\s*[)）]'
    r'\s*[—–\-]*\s*(?:人物研究|传记|傳記|生平事迹|生平事蹟)'
)
_PERSON_BIO_MARKER = r'[，,、\s]{0,3}字[\u3400-\u9fff]{1,5}[，,、\s]{0,3}(?:号|號)[\u3400-\u9fff]{1,5}'
_PERSON_MENTION = (
    r'[，,、\s]{0,3}(?:生于|生於|出生|去世|卒于|卒於|曾任|赴任|将赴任|'
    r'年[一二三四五六七八九十百零〇\d]{1,4}|'
    r'在[^。！？：:\n]{1,14}(?:任内|任內|任上|为官|為官)|'
    r'(?:于|於)(?:康熙|雍正|乾隆|嘉庆|嘉慶|道光|咸丰|咸豐|同治|光绪|光緒|宣统|宣統|\d{4}年))'
)


def title_subject_mentions(title, segs):
    """Return book-local person mentions supported by title and biographical evidence."""
    leading = _PERSON_TITLE_LEAD.match(str(title or '').lstrip('《〈 '))
    if not leading or not _is_xing(leading[0][0]):
        return []
    usable = [row for row in segs if name_evidence_segment(row)]
    text = [row.get('文本') or '' for row in segs if not row.get('source_layout_suspect')
            and not row.get('source_issue') and (row.get('source_role') or row.get('source_kind')) != 'toc']
    for length in range(len(leading[0]), 1, -1):
        name = leading[0][:length]
        word = re.escape(name)
        corroboration = re.compile(word + '(?:' + _PERSON_SOURCE_MARKER + '|' + _PERSON_BIO_MARKER + ')')
        if not any(corroboration.search(t) for t in text):
            continue
        body_match = re.compile(word + '(?:' + _PERSON_MENTION + '|' + _PERSON_BIO_MARKER + ')')
        mentions = []
        for row in usable:
            match = body_match.search(row.get('文本') or '')
            if match:
                mentions.append((name, match.group(0), row))
        if len(mentions) >= 2:
            return mentions
    return []


