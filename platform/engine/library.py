    # 实测红楼梦抽出「云道」「平儿道」「李紈道」「都笑道」「薛蟠道」——
    # 全都通过姓氏法与对白法两道检验，因为「平儿道：」确实形如「姓名+说」。
    # 判据只能用尾字：「道/说/笑/问/答/叫/喊/骂/哼/叹」收尾的一律剔除，
    # 真实人名以这些字收尾的概率极低（「贾琏」「宝玉」「黛玉」都不沾）。
    SPEECH_TAIL = re.compile(r'(?:说道|笑道|叫道|问道|答道|骂道|喝道|道|说|笑|问|答|叫|喊|骂|哼|叹|嚷|詈)$')
    # 非人名尾字：以这些字收尾的「姓+字」几乎都是虚词或疑问短语被切出来的。
    # 实测红楼梦抽出「利害」「何事」「那里來」「那邊去」「何苦來」「那一個」「管這」
    # —— 全是因为首字碰巧是姓（利/何/那/管 都在百家姓或姓氏近似表里）。
    # 这条比姓氏表更管用：姓氏表只能管开头，句法只能在结尾露馅。
    NONAME_TAIL = set('來来去事个個這这那的了吗呢吧啊么麼甚谁誰啥')
    # 疑问/指示/介词打头：这类词的第一个字常进姓氏表（何/那/管/甚/谁/向/和/与）。
    # 实测红楼梦抽出「向寶玉」「向黛玉」「向襲人」「向鳳姐」「和寶釵」「和王夫」
    # —— 是「向+人名」「和+人名」的介词短语，不是人名本身。
    # 这些若不剔，图谱里会出现「向寶玉 与 寶玉」两个节点（同一个人）。
    QLEAD = re.compile(r'^(?:何|那|這这|甚|谁|誰|管|多|几|幾|若|如|为|為|不|没|沒|无|無'
                       r'|向|和|与|與|同|对|對|把|被|给|給|跟|替|帮|幫|叫|让|讓)')
    # 情绪/动作词：不是人名。实测红楼梦抽出的「高興」「冷笑」「都笑」属此类。
    MOOD = {'高兴', '高興', '冷笑', '都笑', '忙笑', '笑道', '说着', '說著', '听了', '听了',
            '一面', '众人', '眾人', '大家', '自己', '别人', '別人', '二人', '三人', '那人',
            '此人', '有人', '无人', '無人', '只此', '如此', '这般', '這般', '那日', '這日',
            '胡说', '胡說', '都说', '都說', '说道', '說道', '只说', '又說', '便说', '便說',
            '问道', '問道', '答道', '欢喜', '歡喜', '喜欢', '喜歡', '烦恼', '煩惱',
            '着急', '著急', '生气', '生氣', '叹气', '歎气', '相干'}   # 相干：红楼梦 59 次，姓法把「相」当姓
    # 名词/量词/方位词：姓氏法会把这些词的第一个字当姓。
    # 实测「房里」→「房」作姓、「房子」→「房」作姓、「许多」→「许」作姓，
    # 三者频次都极高（100+），排在真人物之前。
    NOUN = {'房里', '房子', '屋里', '门外', '家中', '家里', '身上', '心中',
            '许多', '若干', '一些', '多少', '几个', '两个', '三个',
            '东西', '南北', '东西', '上下', '左右', '前后', '里头', '外头',
            '上面', '下面', '前面', '后面', '旁边', '中间', '时间', '时候'}
    # 三字候选集合：用于识别「二字残词」。
    # 若「林黛玉」是候选，则「林黛」必是切半产物，不能单列。
    # 注意判据是「二字词是否为某个三字词的前缀」，不是「二字词是否在三字集合里」——
    # 「林黛」永远不会等于「林黛玉」，写 `w in tri` 恒为 False，
    # 结果是残词一条都过滤不掉（实测「林黛」264 次照样进表）。
    tri = {w for w, n in A.items() if len(w) == 3 and n >= 3}
    tri_pref = {w[:2] for w in tri}
    rows = []
    for w, na in A.most_common(topk * 40):
        if w in C_BAD_PHRASES:
            continue
        if w in BAD or w in COMMON or w in MOOD or w in NOUN:
            continue
        # A 通道此前**没有**走 C_BAD_RE / C_BAD2 / C_BAD_LEAD / GENERIC 这几道，
        # 于是同一批噪音从姓氏法漏了进来。实测西游记：
        #   「空中」(空 是姓) 65 次、「金箍棒」(金 是姓) 33 次、
        #   「聞說」「路傍」「諸天」「高聲」「王聞言」全部通过姓氏法。
        # 两条通道必须共用同一套词形过滤，否则修一条漏一条。
        if w in GENERIC or w in COMMENT or w in AUTHOR_SELF:
            continue
        if C_BAD_RE.match(w) or C_BAD_LEAD.match(w) or C_BAD2.match(w):
            continue
        if len(w) >= 3 and w[-1] in '暗聞闻聽听見见道說说笑問问答答想知忙又便忽猛':
            continue
        if w[-1] in BAD_TAIL or w[-1] in NONAME_TAIL:
            continue
        if SPEECH_TAIL.search(w):
            continue
        if QLEAD.match(w):
            continue
        # 残词剔除：二字候选若是某个够常见三字候选的前缀，判为切半产物
        if len(w) == 2 and w in tri_pref:
            continue
        nb = B.get(w, 0)
        freq = sum(s['文本'].count(w) for s in segs if w in s['文本'])
        if freq < 4:
            continue
        span = len({s['篇'] for s in segs if w in s['文本']})
        # 分布广度这条判据只用来挡「满书都是的虚词」，但必须放宽到 0.85：
        # 主角恰恰分布最广（红楼梦「寶玉」117/120 篇），
        # 0.6 会把主角挡掉。真正的虚词已被 BAD/MOOD/NOUN 与尾字规则拦下，
        # 这里只兜住「通篇均匀分布的功能词」这一种极端情形。
        if span > nseg * 0.85:
            continue
        # 姓氏法命中率要高：真正的人名，汉字里「姓+名」形态反复出现，
        # 一个常用词（满意/关于/文化）被切成「姓+字」的次数远低于其词频。
        # 要求 na ≥ freq*0.5，即一半以上出现都呈「姓氏形态」，否则判为虚词。
        if na < freq * 0.5 or na < 5:
            continue
        # 命名合法性：名字不能以虚词字收尾，也不能是常见名词尾
        if w[-1] in BAD_TAIL:
            continue
        # 置信：对白证据是硬证据。
        # 门槛从 nb>=2 提到 nb>=3，且要求对白归属占频次的一定比例 ——
        # 纯靠「形如姓名」判不出真假（「利害」「房門」「方子」形态全合法），
        # 但对白归属能：真人名会反复出现在「XX道：『…』」的说话人位置，
        # 虚词名词几乎不会（实测红楼梦「房門」对白归属 2 次、「利害」1 次，
        # 而「平儿」98 次、「薛姨媽」37 次，差两个数量级）。
        if nb >= 3 and nb >= freq * 0.02:
            conf = '强证据'
        elif nb >= 1:
            conf = '弱证据'
        else:
            continue
        hits = [s for s in segs if w in s['文本']]
        rows.append({'人物': w, '通名': False, '频次': freq,
                     '首现': hits[0]['id'], '首现篇': hits[0]['篇'],
                     '分布篇数': span, '姓氏法': na, '对白归属': nb,
                     '来源': '自动候选·待人工确认', '证据': conf})

    # --- 并入 C 通道（无姓氏依赖的说话人法）---
    # 这一步是为了补回「寶玉/寶釵/西門慶/孫悟空」这类不冠姓的主角。
    # C 通道的判据是「出现在说话人位置」，比姓氏法更硬：
    # 「寶玉道：“…”」里的「寶玉」必然是个人，不需要它像人名。
    #
    # ⚠ 这里刻意不套用「分布篇数 > 60% 就丢弃」这条规则 ——
    # 那条规则本意是排除满书散布的虚词，但**主角恰恰是分布最广的人**。
    # 实测红楼梦「寶玉」分布 117/120 篇、「寶釵」99/120 篇，
    # 两条都被 0.6 阈值挡掉，于是全书出现 3923 次的第一主角进不了人物表。
    # 判断「是不是人」只能靠证据类型（说话人位置），不能靠分布广度。
    #
    # ---- 开关：这本书的说话人法是否已经跑偏 ----
    # 判据是「说话人位置切出来的候选里，状语形态占多少」。
    # 章回体与文言：「寶玉笑道」「玄德曰」—— 说话动词前就是名字，干净。
    # 现代白话：老舍写「瑞宣先笑了一下，而后声音很低的说」，
    #   切出来的是状语（低声/心里/而恳切/极恳切/音很低/不客气）。
    # 这个比例可以直接从 C 里量出来，不需要书型标签，也不需要书名硬编码。
    #
    # 实测（C 通道 top50 里以状语字收尾的次数 ÷ C 总次数），全库排序：
    #   故事新编 0.153 / 四世同堂上册 0.135 / 四世同堂中册 0.112
    #   呐喊 0.095 / 四世同堂下册 0.092 / 野草 0.065
    #   ──────────── 以上是现代白话，位置特征失效 ────────────
    #   红楼梦 0.043 / 西游记 0.026 / 儒林外史 0.010 / 金瓶梅 0.000
    # 阈值取 0.058，落在「野草 0.065」与「红楼梦 0.043」之间。
    # ⚠ 另加 C 总样本 ≥50 的门槛：文心雕龙只有 8 个样本却算出 0.125，
    #   小样本的比例不能当判据（这是本项目第三次栽在「小分母」上）。
    #
    # ⚠ 之前的写法是数「…的」结尾的键，但 _STRIP_TAIL 会先把「的」剥掉，
    #   那个键根本不存在，占比永远算成 0.004，开关永不触发 —— 已修正。
    _ADV_END = set('低高声慢快切肃强忙连紧迟讪意儿脸好')
    _ADV_FORMS = sum(n for w, n in C.most_common(50)
                     if w and (w[-1] in _ADV_END or w[-1] in '的地'))
    _C_TOT = sum(C.values()) or 1
    _USE_INI_RATE = (_C_TOT >= 50) and ((_ADV_FORMS / _C_TOT) >= 0.058)
    have = {r['人物'] for r in rows}
    for w, nc in C.most_common(topk * 20):
        if len(w) < 2 or w in have:
            continue
        if w in C_BAD_PHRASES:
            continue
        if w in BAD or w in COMMON or w in MOOD or w in NOUN or w in C_BAD:
            continue
        if w in GENERIC or w in COMMENT or w in AUTHOR_SELF:
            continue
        if C_BAD_RE.match(w) or C_BAD_LEAD.match(w) or C_BAD2.match(w):
            continue
        # 「行者暗」「王聞言」「猴王聽」：人名 + 动作被切在一起。
        # 判据是尾字落在动作/感知字上（暗/聞/听/見/道/說/笑/問/答），
        # 不是靠词表 —— 否则每本书都要重列一遍。
        if len(w) >= 3 and w[-1] in '暗聞闻聽听見见道說说笑問问答答想知忙又便忽猛':
            continue
        if w[-1] in BAD_TAIL or w[-1] in NONAME_TAIL or w[-1] in C_BAD_TAIL or w[-1] in C_BAD_TAIL2:
            continue
        if SPEECH_TAIL.search(w) or QLEAD.match(w):
            continue
        # 三字以上的「X笑」「X忙」「X点头」是「人名+动作」，切掉尾字再判
        if len(w) >= 3 and w[-1] in '笑忙因便又等都想歎歎点點答':
            continue
        freq = sum(s['文本'].count(w) for s in segs if w in s['文本'])
        if freq < 8:
            continue
        span = len({s['篇'] for s in segs if w in s['文本']})
