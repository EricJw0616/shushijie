def graph_ready(segs, rows, pollute=0.0, min_people=6, min_dialog=10):
    """关系图谱准入判定。返回 (能否出图, 原因, 指标)。"""
    from collections import Counter
    hi = [r for r in rows if r.get('证据') == '强证据']
    met = {}
    if len(hi) < min_people:
        return False, (f'强证据人物仅 {len(hi)} 人（需 ≥{min_people}），'
                       f'本类书无稳定对白归属或人名形态，不出关系图谱；'
                       f'如需出图，先人工确认人物名单'), met
    if pollute > 20:
        return False, f'通名污染率 {pollute}%（>20%），关系图谱会串人', met

    # ---- 准入判据：**场景密度**（同段出现 ≥3 个人物的段数 / 有人的段数）----
    #
    # 试过并否掉的三种判据（都记在这里，避免以后再走一遍）：
    #
    #  ①「人物共现率」＝任意两人同段段数/总段数。分母是全书段数，
    #    对长篇天然偏低、对短篇天然偏高，量的其实是「书有多长」。
    #    实测日知录 2.8%、徐霞客 0%、红楼梦 40% —— 看似分得开，
    #    但红楼梦高只是因为段多、人物出现得密，不是因为关系真。
    #
    #  ②「稳定配对」＝有对白的人里，同段 ≥3 次的配对数。
    #    能正确挡下日知录（5~7 对）、徐霞客（0 对），
    #    但把四世同堂（1 对）也挡了 —— 那是误杀。四世同堂全书 2349 对引号，
    #    「某某说」的书面对白极少，老舍大量用动作引导对白
    #    （「冠先生转过脸来，很俊美的一笑：『我出去干点正经的』」），
    #    还有大段不做归属的对话。对白归属抽不出来是**我们的抽取缺陷**，
    #    不是这本书没有人物关系。拿缺陷当判据，等于把「我们抽不到」
    #    说成「这本书没有」。
    #
    #  ③「跨书重复」＝一个词出现在几本书里。想用它筛通用词（一面/有人/孔子），
    #    但四世同堂三册是分卷入库的，「瑞宣」跨 3 本 → 真主角被判通用词。
    #
    # 换成场景密度：同段里同时出现 ≥3 个候选人物，就说明这一段在写
    # 「几个人在一个场合里」，这是**场景**的机械定义，与对白归属无关。
    # 注疏/语录/游记是「一段引一个人」，密度上不去；小说/戏曲是
    # 「一段写一屋子人」，密度自然高。
    #
    # ---- 人工对账（阈值不是试出来的，是这张表对出来的）----
    # 先给每本书一个人工标签：「这本书里是否真有一群互相打交道的人」，
    # 这个判断与我们的抽取能力无关，只看原文。实测场景密度：
    #
    #   标注 YES（真有群像）      密度          标注 NO（没有群像）      密度
    #   金瓶梅                  0.954        日知录                0.153
    #   红楼梦                  0.917        阅微草堂笔记            0.135
    #   三国志演义               0.854        古文观止               0.122
    #   桃花扇                  0.841        聊斋志异               0.088
    #   世说新语                 0.712        闲情偶寄               0.068
    #   西游记                  0.447        徐霞客游记             0.036
    #   儒林外史                 0.312        礼记                  0.230
    #                                       孟子                  0.191
    #
    # 阈值 0.38 落在 NO 最高（礼记 0.230）与 YES 最低（儒林外史 0.312）之上。
    # 说清两件事：
    #  ① 儒林外史被我一开始标成 YES，看了密度才改。它是「一回换一批人」的
    #     链式结构，匡超人、杜少卿、鲍廷玺各自占几个回目就退场，
    #     全书没有稳定的互动群像 —— 密度 0.31 是事实，不是抽取失败。
    #     史记（0.062）同理：130 篇互不相干的人物传记。
    #  ② 西游记 0.447 偏低，是因为它的人物表里通名多（妖精 221 次、
    #     小妖 155 次、老魔 59 次），这些词把「有人段」的分母撑大了。
    #     它的真主角（行者 1832、菩薩 501、大聖 560）密度其实很高。
    #     要修就得先解决「通名 vs 专名」，不属于准入判据的职责。
    #
    # ---- 已知盲区（必须写在页面上，不许当成「这本书没有人物」）----
    # 现代白话小说抽不出来。四世同堂全书 2349 对引号，但「瑞宣说」「瑞宣道」
    # 极少（瑞宣 529 次里只有 9 次挨着说话动词，且后接 `：“` 而非 `道`），
    # 老舍大量用动作引导（「冠先生转过脸来，很俊美的一笑：『我出去…』」）。
    # 纯正则在这里必然失效：人物名不带姓（瑞宣/大赤包/小崔），
    # 说话人靠语序与动作提示，不是固定词形。这类书标为「抽不出」而不是
    # 「没有人物关系」—— 两者在数据里必须分开，前者是能力边界，
    # 后者是关于书的结论。
    #
    # 阈值 0.38 的来历：见下面「人工对账」一节，不是试出来的，是对账对出来的。
    names = [r['人物'] for r in hi]
    seg1 = seg3 = 0
    for s in segs:
        t = s['文本']
        k = sum(1 for n in names if n in t)
        if k >= 1:
            seg1 += 1
        if k >= 3:
            seg3 += 1
    dens = seg3 / max(1, seg1)
    met = {'强证据人数': len(hi), '有人段数': seg1, '三人同段段数': seg3,
           '场景密度': round(dens, 3)}
    if dens < 0.38:
        return False, (f'场景密度 {dens:.2f}（同段出现 ≥3 人的段数占 {seg3}/{seg1}，'
                       f'需 ≥0.38）：书里没有「几个人同处一个场合」的场景，'
                       f'人物是被引用的古人、注家或泛称，'
                       f'出图谱只会得到一张没有边的散点图'), met
    return True, (f'强证据人物 {len(hi)} 人，场景密度 {dens:.2f}'
                  f'（{seg3}/{seg1} 段有 ≥3 人同场），可出图谱（仍建议先确认名单）'), met


def outline_index(segs):
    """结构索引：篇 → 段数、字数、首末锚点。"""
    d = {}
    for s in segs:
        if s['篇序'] == 0:
            continue
        a = d.setdefault(s['篇序'], {'篇序': s['篇序'], '篇': s['篇'],
                                     '段数': 0, '字数': 0,
                                     '首锚点': s['id'], '末锚点': s['id']})
        a['段数'] += 1
        a['字数'] += s['字数']
        a['末锚点'] = s['id']
    return [d[k] for k in sorted(d)]


def stats(segs):
    body = [s for s in segs if s['篇序'] > 0] or segs
    h = sum(s['字数'] for s in body)
    lens = [s['字数'] for s in body] or [0]
    return {'汉字': h, '段数': len(body), '均段字': round(sum(lens) / len(lens), 0),
            '最短段': min(lens), '最长段': max(lens)}


